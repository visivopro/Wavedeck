// Classic text.bmp character grid: [row, column] in 5x6 cells.
export const FONT_LOOKUP = {
  '"': [0, 26], '@': [0, 27], ' ': [0, 30],
  '…': [1, 10], '.': [1, 11], ':': [1, 12], '(': [1, 13], ')': [1, 14], '-': [1, 15], "'": [1, 16], '!': [1, 17],
  _: [1, 18], '+': [1, 19], '\\': [1, 20], '/': [1, 21], '[': [1, 22], ']': [1, 23], '^': [1, 24], '&': [1, 25],
  '%': [1, 26], ',': [1, 27], '=': [1, 28], $: [1, 29], '#': [1, 30],
  'Å': [2, 0], 'Ö': [2, 1], 'Ä': [2, 2], '?': [2, 3], '*': [2, 4],
  '<': [1, 22], '>': [1, 23], '{': [1, 22], '}': [1, 23],
};
'abcdefghijklmnopqrstuvwxyz'.split('').forEach((c, i) => { FONT_LOOKUP[c] = [0, i]; });
'0123456789'.split('').forEach((c, i) => { FONT_LOOKUP[c] = [1, i]; });

export function lookupChar(ch) {
  const lower = ch.toLowerCase();
  if (FONT_LOOKUP[lower]) return FONT_LOOKUP[lower];
  // Fold accented characters to their base letter
  const base = lower.normalize('NFD').replace(/[̀-ͯ]/g, '');
  return FONT_LOOKUP[base] || FONT_LOOKUP[' '];
}

// Draw pixel text with the 3x5 font. Returns width drawn.
export function pixelText(ctx, str, x, y, color, spacing = 1) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (g[r][c] === '#') ctx.fillRect(cx + c, y + r, 1, 1);
    cx += 3 + spacing;
  }
  return cx - x - spacing;
}
export const pixelTextWidth = (str, spacing = 1) => String(str).length * (3 + spacing) - spacing;
